/* --- 요일 조립기: 원본 시트의 블록 순서를 그대로 따름 --- */
function chestBack(bench,incline,inclineN,pendlay,row,rowN,bSpecA,bSpecB){
  return [
    [ main("벤치프레스",bench),
      sub("인클라인 벤치",rep(incline,inclineN)),
      ...(bSpecA?[pick("보조운동 B",bSpecA,P_CHEST)]:[]) ],
    [ main("펜들레이로우",pendlay),
      sub("바벨로우",rep(row,rowN)),
      ...(bSpecB?[pick("보조운동 B",bSpecB,P_BACK)]:[]) ]
  ];
}
function quadSho(squat,front,frontN,ohp,bnp,bnpN,bSpecA,bSpecB){
  return [
    [ main("스쿼트",squat),
      sub("프론트 스쿼트",rep(front,frontN)),
      ...(bSpecA?[pick("보조운동 B",bSpecA,P_QUAD)]:[]) ],
    [ main("OHP",ohp),
      sub("비하인드 넥 프레스",rep(bnp,bnpN)),
      ...(bSpecB?[pick("보조운동 B",bSpecB,P_SHO)]:[]) ]
  ];
}
function hamArm(dead,dead2,close,bSpec,armSpec){
  return [
    [ main("데드리프트",dead),
      ...(dead2?[sub("데드리프트2",dead2)]:[]),
      ...(bSpec?[pick("보조운동 B",bSpec,P_HAM)]:[]) ],
    [ main("클로즈벤치",close,"삼두 메인"),
      ...(armSpec?[pick("삼두 B",armSpec,P_TRI),
                   pick("이두 B1",armSpec,P_BI),
                   pick("이두 B2",armSpec,P_BI)]:[]) ]
  ];
}
function rep(set,n){const a=[];for(let i=0;i<n;i++)a.push(set);return a}

